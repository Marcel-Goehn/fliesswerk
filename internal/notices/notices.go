// Package notices renders THIRD_PARTY_NOTICES: the license and NOTICE texts
// of every module compiled into a shipped binary, which their licenses want
// to travel with binary copies. It reads only the module graph and the module
// cache, so it runs offline.
package notices

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/Marcel-Goehn/fliesswerk/internal/proxyimage"
)

//go:generate go run ./gen

// FileName is the file Render's text goes in, at the repo root.
const FileName = "THIRD_PARTY_NOTICES"

// A platform a binary is built for.
type target struct{ goos, goarch string }

// A binary a release ships, and the targets it is built for.
type binary struct {
	pkg     string
	targets []target
}

// shipped mirrors .goreleaser.yaml's builds, and the proxy proxyimage embeds.
var shipped = []binary{
	{".", []target{
		{"linux", "amd64"}, {"linux", "arm64"},
		{"darwin", "amd64"}, {"darwin", "arm64"},
		{"windows", "amd64"}, {"windows", "arm64"},
	}},
	{"./internal/egress/proxycmd", proxyTargets()},
}

func proxyTargets() []target {
	var ts []target
	for _, arch := range proxyimage.Arches {
		ts = append(ts, target{"linux", arch})
	}
	return ts
}

// The files at a module's root that carry its license, and those that carry
// its notices: a NOTICE, or the PATENTS grant Go's own repos ship.
var (
	licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying)([-._].*)?$`)
	noticeFile  = regexp.MustCompile(`(?i)^(notice|patents)([-._].*)?$`)
)

const (
	rule    = "================================================================================\n"
	subRule = "--------------------------------------------------------------------------------\n"
)

const preamble = `Third-party notices for Fliesswerk

The fliesswerk executable, and the egress proxy embedded in it, contain code
from the modules below. Their licenses and notices follow, each after the
modules it applies to. Fliesswerk's own license is in LICENSE.

Generated by ` + "`go generate ./internal/notices`" + ` from the module graph; don't edit.
`

// A module linked into a shipped binary.
type module struct {
	path, version, dir string
}

// Render returns the text of THIRD_PARTY_NOTICES for the module this runs in.
func Render() ([]byte, error) {
	root, err := goOutput("", nil, "list", "-m", "-f", "{{.Dir}}\t{{.GoVersion}}")
	if err != nil {
		return nil, err
	}
	rootDir, goVersion, _ := strings.Cut(strings.TrimSpace(root), "\t")
	goroot, err := goOutput(rootDir, nil, "env", "GOROOT")
	if err != nil {
		return nil, err
	}

	mods := map[string]module{}
	for _, b := range shipped {
		for _, t := range b.targets {
			if err := addLinked(mods, rootDir, b.pkg, t); err != nil {
				return nil, err
			}
		}
	}
	all := []module{{path: "Go standard library", version: "go" + goVersion, dir: strings.TrimSpace(goroot)}}
	for _, p := range sortedKeys(mods) {
		all = append(all, mods[p])
	}

	// Modules with the same license and notice share one copy of them.
	var order []string
	groups := map[string][]module{}
	for _, m := range all {
		text, err := legalText(m)
		if err != nil {
			return nil, err
		}
		if _, ok := groups[text]; !ok {
			order = append(order, text)
		}
		groups[text] = append(groups[text], m)
	}

	var out bytes.Buffer
	out.WriteString(preamble)
	for _, text := range order {
		out.WriteString("\n" + rule)
		for _, m := range groups[text] {
			fmt.Fprintf(&out, "%s %s\n", m.path, m.version)
		}
		out.WriteString(rule)
		out.WriteString(text)
	}
	return out.Bytes(), nil
}

// addLinked adds to mods every module whose packages pkg links on target.
func addLinked(mods map[string]module, rootDir, pkg string, t target) error {
	env := []string{"GOOS=" + t.goos, "GOARCH=" + t.goarch}
	data, err := goOutput(rootDir, env, "list", "-deps", "-json=Module", pkg)
	if err != nil {
		return err
	}
	type mod struct {
		Path, Version, Dir string
		Main               bool
		Replace            *mod
	}
	dec := json.NewDecoder(strings.NewReader(data))
	for {
		var p struct{ Module *mod }
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			return nil
		} else if err != nil {
			return fmt.Errorf("go list %s for %s/%s: %w", pkg, t.goos, t.goarch, err)
		}
		m := p.Module
		if m == nil || m.Main {
			continue // the standard library, or Fliesswerk itself
		}
		if m.Replace != nil {
			m.Version, m.Dir = m.Replace.Version, m.Replace.Dir
		}
		if m.Dir == "" {
			return fmt.Errorf("%s %s isn't in the module cache; run `go mod download`", m.Path, m.Version)
		}
		mods[m.Path] = module{path: m.Path, version: m.Version, dir: m.Dir}
	}
}

// legalText is m's license files, then its notice files, each under its name.
func legalText(m module) (string, error) {
	entries, err := os.ReadDir(m.dir)
	if err != nil {
		return "", err
	}
	var licenses, notices []string
	for _, e := range entries {
		switch {
		case e.IsDir():
		case licenseFile.MatchString(e.Name()):
			licenses = append(licenses, e.Name())
		case noticeFile.MatchString(e.Name()):
			notices = append(notices, e.Name())
		}
	}
	if len(licenses) == 0 {
		return "", fmt.Errorf("%s %s has no license file in %s", m.path, m.version, m.dir)
	}
	var b strings.Builder
	for i, name := range append(licenses, notices...) {
		data, err := os.ReadFile(filepath.Join(m.dir, name)) //nolint:gosec // a file at a module's root
		if err != nil {
			return "", err
		}
		if i > 0 {
			b.WriteString("\n" + subRule)
		}
		b.WriteString(name + ":\n\n")
		text := strings.ReplaceAll(string(data), "\r\n", "\n")
		b.WriteString(strings.TrimRight(text, " \t\n") + "\n")
	}
	return b.String(), nil
}

// goOutput runs the go command offline, on the module cache alone.
func goOutput(dir string, env []string, args ...string) (string, error) {
	cmd := exec.Command("go", args...) //nolint:gosec // the go command with our own arguments
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOPROXY=off", "GOFLAGS=-mod=readonly", "GOWORK=off", "CGO_ENABLED=0")
	cmd.Env = append(cmd.Env, env...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go %s: %w\n%s", strings.Join(args, " "), err, stderr.String())
	}
	return string(out), nil
}

func sortedKeys(m map[string]module) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
